};

/// Respuesta de `GET /ventas/mias/:id/pagos`.
Map<String, dynamic> resumenPagosJson({
  int total = 56000,
  int recibido = 0,
  int enRevision = 0,
  int falta = 0,
  List<Map<String, dynamic>> pagos = const [],
}) => {
  'total': total,
  'recibido': recibido,
  'en_revision': enRevision,
  'falta': falta,
  'saldo_a_favor': 0,
  'pagos': pagos,
};
