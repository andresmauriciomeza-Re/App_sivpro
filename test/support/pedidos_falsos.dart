  'devolucion_estado': devolucionEstado,
  'devolucion_tipo': devolucionTipo,
  'devolucion_monto': null,
  'devolucion_nota': devolucionNota,
  'metodo_reembolso': null,
  'id_venta_reemplazo': idVentaReemplazo,
  'segundos_restantes_anulacion': segundos,
